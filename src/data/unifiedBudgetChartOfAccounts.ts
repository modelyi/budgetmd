// =========================================================================
// 甜甜圈集团公司全面预算管理系统 - 统一预算科目主数据与编码规则库
// (Unified Budget Chart of Accounts Master Data & Coding Rules Standard)
// 包含四大体系：
// 1. PL: 利润表科目 (Profit & Loss / Income Statement)
// 2. BS: 资产负债表科目 (Balance Sheet)
// 3. CF: 现金流量表科目 (Cash Flow Statement)
// 4. FY: 费用与支出预算科目 (Expense & Expenditure Budget Subjects - 明细见 AA.3.b)
// =========================================================================

export type BudgetSubjectFamily = 'PL' | 'BS' | 'CF' | 'FY';

export type BudgetSubjectCategory =
  | '利润表-营业收入'
  | '利润表-营业成本'
  | '利润表-期间费用'
  | '利润表-税金与附加'
  | '利润表-其他收益与投资'
  | '利润表-利润汇总与所得税'
  | '资产负债表-流动资产'
  | '资产负债表-非流动资产'
  | '资产负债表-流动负债'
  | '资产负债表-非流动负债'
  | '资产负债表-所有者权益'
  | '现金流量表-经营活动'
  | '现金流量表-投资活动'
  | '现金流量表-筹资活动'
  | '现金流量表-现金及等价物'
  | '费用支出-经营性费用(OpEx)'
  | '费用支出-资本性支出(CapEx)'
  | '费用支出-综合汇总'
  | '关联交易-代采购'
  | '关联交易-内部职场租赁'
  | '关联交易-资产转卖'
  | '关联交易-加成与抵销';

export interface BudgetAccountCodingRule {
  family: BudgetSubjectFamily;
  prefix: string;
  familyName: string;
  codePattern: string;
  exampleCode: string;
  description: string;
  levelRules: { level: number; format: string; sample: string; desc: string }[];
  associatedStatements: string[];
  governingStandards: string;
}

export interface UnifiedBudgetAccountItem {
  code: string;               // 科目编码 (如 6001, 6001.1, 1122, 1405, CF-01)
  name: string;               // 科目名称
  fullName: string;           // 科目全称
  family: BudgetSubjectFamily;// 科目家族 (PL / BS / CF / FY)
  category: BudgetSubjectCategory; // 明细分类
  level: 1 | 2 | 3 | 4;       // 科目层级
  parentCode?: string;        // 上级科目编码
  balanceDirection: '借' | '贷' | '流入' | '流出' | '净额' | '汇总';
  isReportLineItem: boolean;  // 是否直接构成三大财务报表列报行
  isExpenseSubject: boolean;  // 是否属于费用/支出预算科目 (预算科目的一种)
  expenseType?: '经营性支出' | '资本性支出' | '';
  isImmutable: boolean;       // 是否系统确定基准 (法定不可篡改)
  budgetSourceWorkbench: string; // 归属编制表/工作台 (如 B.1 销售收入 / B.5 期间费用 / 1.10 三表)
  mappedPLCode?: string;      // 关联利润表科目编码
  mappedBSCode?: string;      // 关联资产负债表科目编码
  mappedCFCode?: string;      // 关联现金流量表科目编码
  description: string;        // 核算范围与业务说明
  accountingStandardRef: string; // 会计准则依据
}

