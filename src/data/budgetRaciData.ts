// A1.RACI 清单「涉及部门」筛选选项
//   选项集 = 矩阵列（RACI_DEPARTMENTS 12 大权责主体）
//          ∪ 清单行级责任字段（responsibleDept / accountable / consulted / informed）中出现过的实际部门（按 、/，拆解去重）
