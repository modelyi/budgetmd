/**
 * 全面预算编制责任 RACI 矩阵核心数据与总体流程定义
 * 适用行业：设备制造行业（贯通 签约订单 → 生产制造 → 供应链采购 → CAPEX/OPEX → 资金税金 → 财务三表）
 * 
 * 总体流程三阶段十步骤规范：
 * 阶段一：准备与启动阶段
 *   1.1 维护/导入基础数据
 *   1.2 预算启动
 * 阶段二：前提与假设阶段
 *   2.1 预算假设项维护
 *   2.2 前置信息收集
 * 阶段三：编审与出表阶段
 *   3.1 业务编制
 *   3.2 财务编制
 *   3.3 税费填报
 *   3.4 内部往来处理
 *   3.5 手工填调整
 *   3.6 出表与调整
 * 
 * RACI 角色定义：
 * - R (Responsible / 主责执行): 负责该项预算的数据收集、模型测算与表格填报
 * - A (Accountable / 终审负责): 对该项预算结果的合理性与目标达成负最终签批责任（单一终审人原则）
 * - C (Consulted / 协助咨询): 编制过程中提供专业定额、基准参数、价格/费率审核或前置输入
 * - I (Informed / 知情报送): 预算审批下达后作为工作依据必须知情掌握的相关单位及审计监察部门
 */

export type ProcessStepCode =
  | '1.1'
  | '1.2'
  | '2.1'
  | '2.2'
  | '3.1'
  | '3.2'
  | '3.3'
  | '3.4'
  | '3.5'
  | '3.6';

